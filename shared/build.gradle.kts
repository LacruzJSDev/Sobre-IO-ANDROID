// Supabase connection comes from local.properties (git-ignored), so no environment is baked into the repository.
// Reading it through a provider makes the file an input of the configuration cache.
val localProperties = providers.fileContents(rootProject.layout.projectDirectory.file("local.properties"))
    .asText
    .orElse("")
    .map { text -> Properties().apply { load(text.reader()) } }

fun localProperty(name: String): Provider<String> = localProperties.map { it.getProperty(name).orEmpty() }

// Missing values fall back to the local stack as seen from the Android emulator
val localSupabaseUrl = localProperty("SUPABASE_URL").map { it.ifBlank { "http://10.0.2.2:54321" } }

/**
 * Writes `AppConfig`, the multiplatform replacement of Android's `BuildConfig`. Its inputs are the property values,
 * so the task is up to date until local.properties changes.
 */
abstract class GenerateAppConfig : DefaultTask() {
    @get:Input abstract val supabaseUrl: Property<String>
    @get:Input abstract val supabaseUrlIos: Property<String>
    @get:Input abstract val supabasePublishableKey: Property<String>
    @get:Input abstract val googleWebClientId: Property<String>
    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        fun String.literal() = "\"" + replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""
        val file = outputDir.get().asFile.resolve("dev/lacruzjs/sobreio/AppConfig.kt")
        file.parentFile.mkdirs()
        file.writeText(
            """
            |package dev.lacruzjs.sobreio
            |
            |// Generated by :shared:generateAppConfig from local.properties. Do not edit.
            |internal object AppConfig {
            |    const val SUPABASE_URL = ${supabaseUrl.get().literal()}
            |    const val SUPABASE_URL_IOS = ${supabaseUrlIos.get().literal()}
            |    const val SUPABASE_PUBLISHABLE_KEY = ${supabasePublishableKey.get().literal()}
            |    const val GOOGLE_WEB_CLIENT_ID = ${googleWebClientId.get().literal()}
            |}
            |
            """.trimMargin(),
        )
    }
}

val generateAppConfig = tasks.register<GenerateAppConfig>("generateAppConfig") {
    supabaseUrl.set(localSupabaseUrl)
    // The iOS simulator shares the Mac's network, so the host is 127.0.0.1 there; the Android emulator needs 10.0.2.2
    supabaseUrlIos.set(
        localProperty("SUPABASE_URL_IOS").zip(localSupabaseUrl) { ios, url -> ios.ifBlank { url.replace("10.0.2.2", "127.0.0.1") } },
    )
    supabasePublishableKey.set(localProperty("SUPABASE_PUBLISHABLE_KEY"))
    // Google sign-in is hidden while this is blank. It is the Google *web* client id (Supabase validates tokens against it)
    googleWebClientId.set(localProperty("GOOGLE_WEB_CLIENT_ID"))
    outputDir.set(layout.buildDirectory.dir("generated/appConfig"))
}

